#!/usr/bin/env python3
"""Generate a Ren'Py gallery for the 54 approved provisional static renders.

The images are existing, byte-for-byte copies listed in the local sprite
manifest. This script does not create or edit images and does not generate mouth
or posture variations.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
GAME = PROJECT / "game"
IMAGE_ROOT = GAME / "images"
SPRITE_MANIFEST = IMAGE_ROOT / "masters" / "sprites" / "manifest.json"
OUTPUT = GAME / "technosutra_masters.rpy"

EXPECTED_RENDER_IDS = (
    list(range(1, 43))
    + list(range(44, 52))
    + list(range(53, 57))
)
MISSING_SLOT_IDS = {43, 52}


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def load_assets() -> tuple[list[int], dict[int, dict]]:
    if not SPRITE_MANIFEST.is_file():
        raise SystemExit(f"Missing provisional sprite manifest: {SPRITE_MANIFEST}")
    manifest = json.loads(SPRITE_MANIFEST.read_text(encoding="utf-8"))
    if manifest.get("status") != "provisional" or manifest.get("temporaryUseApprovedByOwner") is not True:
        raise SystemExit("Sprite manifest must record owner-approved provisional use")

    records: dict[int, dict] = {}
    for asset in manifest.get("assets", []):
        number = int(asset["chapter"])
        if number in records:
            raise SystemExit(f"Duplicate provisional sprite manifest entry for ID {number}")
        records[number] = asset

    if sorted(records) != EXPECTED_RENDER_IDS:
        raise SystemExit(
            "Sprite manifest IDs differ from the verified inventory: "
            f"found {sorted(records)}, expected {EXPECTED_RENDER_IDS}"
        )

    assets: dict[int, dict] = {}
    for number in EXPECTED_RENDER_IDS:
        record = records[number]
        if record.get("status") != "provisional":
            raise SystemExit(f"ID {number} is not labeled provisional in the manifest")
        if record.get("upstreamFile") != f"models/modelo{number}.glb":
            raise SystemExit(f"ID {number} has an unexpected upstream model reference")
        relative_file = record.get("file")
        source_capture = record.get("sourceCapture")
        if not isinstance(relative_file, str) or Path(relative_file).is_absolute() or ".." in Path(relative_file).parts:
            raise SystemExit(f"ID {number} has an invalid staged file path: {relative_file!r}")
        if not isinstance(source_capture, str) or Path(source_capture).is_absolute() or ".." in Path(source_capture).parts:
            raise SystemExit(f"ID {number} has an invalid source capture path: {source_capture!r}")
        if not relative_file.startswith("masters/sprites/provisional/"):
            raise SystemExit(f"ID {number} does not reference the existing provisional folder")
        staged_path = IMAGE_ROOT / relative_file
        source_path = IMAGE_ROOT / source_capture
        if not staged_path.is_file():
            raise SystemExit(f"ID {number} references a missing runtime image: {staged_path}")
        expected_hash = record.get("sha256")
        if not expected_hash or sha256(staged_path) != expected_hash:
            raise SystemExit(f"ID {number} failed runtime-image SHA-256 verification")
        # Raw capture files are retained locally for provenance, but are not
        # duplicated in compact CI checkouts or in the shipped game. When a
        # capture is present, verify that it still matches the recorded hash.
        if source_path.is_file() and sha256(source_path) != expected_hash:
            raise SystemExit(f"ID {number} failed source-capture SHA-256 verification")
        if record.get("copiedByteForByte") is not True:
            raise SystemExit(f"ID {number} is not marked as an unmodified copy")
        assets[number] = record

    if manifest.get("availableCount") != len(assets) or len(assets) != 54:
        raise SystemExit(f"Expected exactly 54 vetted provisional renders; found {len(assets)}")
    return EXPECTED_RENDER_IDS, assets


def build_script(numbers: list[int], assets: dict[int, dict]) -> str:
    relative_files = {
        number: f"images/{assets[number]['file']}"
        for number in numbers
    }
    lines = [
        "# Generated by tools/generate_master_sprite_script.py. Do not edit by hand.",
        "# Existing static transparent renders only; all are explicitly provisional.",
        "# Chapter-slot associations follow the verified capture manifest; no names or variants are invented.",
        "# Slots 43 and 52 have no source GLB/render and are deliberately absent.",
        "",
        "default technosutra_master_gallery_index = 0",
        "",
        "init python:",
        f"    TECHNOSUTRA_PROVISIONAL_RENDER_IDS = {numbers!r}",
        f"    TECHNOSUTRA_PROVISIONAL_RENDER_FILES = {relative_files!r}",
        "",
        "transform technosutra_provisional_gallery_portrait:",
        "    xalign 0.5",
        "    yalign 0.78",
        "    zoom 0.68",
        "",
    ]
    for number in numbers:
        lines.append(
            f"image gallery_master_{number:02d}_provisional = {quoted(relative_files[number])}"
        )

    lines.extend([
        "",
        "label technosutra_master_gallery:",
        "    $ technosutra_master_gallery_index = 0",
        "    while True:",
        "        call screen technosutra_master_gallery_screen",
        '        if _return == "next":',
        "            $ technosutra_master_gallery_index = (technosutra_master_gallery_index + 1) % len(TECHNOSUTRA_PROVISIONAL_RENDER_IDS)",
        '        elif _return == "previous":',
        "            $ technosutra_master_gallery_index = (technosutra_master_gallery_index - 1) % len(TECHNOSUTRA_PROVISIONAL_RENDER_IDS)",
        "        else:",
        "            jump start",
        "",
        "screen technosutra_master_gallery_screen():",
        "    modal True",
        "    zorder 100",
        '    add Solid("#070916")',
        "    $ _model_id = TECHNOSUTRA_PROVISIONAL_RENDER_IDS[technosutra_master_gallery_index]",
        "    $ _source_file = TECHNOSUTRA_PROVISIONAL_RENDER_FILES[_model_id]",
        '    add expression ("gallery_master_%02d_provisional" % _model_id) at technosutra_provisional_gallery_portrait',
        "    frame:",
        "        xalign 0.5",
        "        yalign 0.97",
        "        xmaximum 1500",
        "        xpadding 30",
        "        ypadding 16",
        '        background Solid("#101326ee")',
        "        vbox:",
        "            spacing 8",
        '            text "PROVISÓRIO — RENDER FRONTAL — SEM FUNDO" size 30 color "#ffd35a" bold True',
        '            text ("ID %02d · %d/%d · %s" % (_model_id, technosutra_master_gallery_index + 1, len(TECHNOSUTRA_PROVISIONAL_RENDER_IDS), _source_file)) size 22 color "#edf1ff"',
        '            text "Imagem estática; sem variações de boca ou postura. O slot segue o manifesto de captura; nomes de personagens não foram inferidos." size 20 color "#d5d9e8"',
        "            hbox:",
        "                spacing 28",
        '                textbutton "Anterior" action Return("previous")',
        '                textbutton "Próximo" action Return("next")',
        '                textbutton "Fechar galeria" action Return("exit")',
        "",
    ])
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--exclude-upstream-renders",
        action="store_true",
        help="write a safe explanatory gallery stub without referencing upstream image files",
    )
    args = parser.parse_args()
    if args.exclude_upstream_renders:
        OUTPUT.write_text(
            "\n".join([
                "# License-safe build stub. Upstream render files are not included.",
                "label technosutra_master_gallery:",
                "    scene bg_intro_scene with fade",
                '    centered "Galeria Technosutra não incluída neste pacote"',
                '    narrator "Os 54 renders brutos do upstream foram mantidos fora do pacote devido ao conflito de licença."',
                "    return",
                "",
            ]),
            encoding="utf-8",
        )
        print(f"Wrote license-safe gallery stub {OUTPUT}; no upstream render files referenced.")
        return 0
    numbers, assets = load_assets()
    OUTPUT.write_text(build_script(numbers, assets), encoding="utf-8")
    print(f"Wrote {OUTPUT}: {len(numbers)} provisional static renders; verified runtime files and SHA-256.")
    print("Missing slots 43 and 52; generated no mouth/posture variants.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
